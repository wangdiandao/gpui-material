"""Regenerate the catalog and desktop fonts from the pinned Google assets."""

import argparse
import hashlib
import re
import shutil
from pathlib import Path

from fontTools import subset, version
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


STYLES = ("Outlined", "Rounded", "Sharp")
FONTTOOLS_VERSION = "4.63.0"
SOURCE_REVISION = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
SOURCE_AXES = "[FILL,GRAD,opsz,wght]"
CRATE = Path(__file__).resolve().parent.parent / "crates" / "symbols"


def font_stem(style):
    return f"MaterialSymbols{style}{SOURCE_AXES}"


def catalog_rows(source):
    codepoints = (source / f"{font_stem(STYLES[0])}.codepoints").read_bytes()
    for style in STYLES[1:]:
        if (source / f"{font_stem(style)}.codepoints").read_bytes() != codepoints:
            raise ValueError(f"{style} has a different codepoint map")

    rows = []
    for line in codepoints.decode("ascii").splitlines():
        name, value = line.split()
        if not re.fullmatch(r"[a-z0-9]+(?:_[a-z0-9]+)*", name):
            raise ValueError(f"Invalid symbol name {name}")
        variant = "".join(word.capitalize() for word in name.split("_"))
        if variant[0].isdigit():
            variant = "N" + variant
        rows.append((name, variant, int(value, 16)))
    for column in (0, 1):
        if len({row[column] for row in rows}) != len(rows):
            raise ValueError("Duplicate symbol names or Rust variants")
    return sorted(rows), hashlib.sha256(codepoints).hexdigest()


def write_catalog(rows):
    output = ["// Generated by xtask/material-symbols.py.", "", "catalog! {"]
    for name, variant, codepoint in rows:
        output.append(f'    {variant} => "{name}", 0x{codepoint:x};')
    output.append("}")
    (CRATE / "src" / "catalog.rs").write_text(
        "\n".join(output) + "\n", encoding="ascii", newline="\n"
    )


def build_font(source, output, codepoints):
    with TTFont(source, recalcTimestamp=False) as font:
        missing = codepoints.difference(font.getBestCmap())
        if missing:
            raise ValueError(f"{source.name} is missing codepoints {sorted(missing)}")
        instantiateVariableFont(font, {"GRAD": 0, "opsz": 24}, inplace=True)
        options = subset.Options()
        options.hinting = False
        options.drop_tables += ["GSUB"]
        keep = subset.Subsetter(options=options)
        keep.populate(unicodes=codepoints)
        keep.subset(font)
        font["name"].setName(
            "Adapted by GPUI Material with fixed grade 0 and optical size 24.",
            10, 3, 1, 0x409,
        )
        font.save(output)


def sha256(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="directory with the upstream fonts, codepoints, and LICENSE")
    args = parser.parse_args()
    if version != FONTTOOLS_VERSION:
        parser.error(f"expected fontTools {FONTTOOLS_VERSION}, got {version}")

    assets = CRATE / "assets"
    rows, codepoints_sha256 = catalog_rows(args.source)
    write_catalog(rows)
    shutil.copyfile(args.source / "LICENSE", assets / "LICENSE")
    manifest = [
        'repository = "https://github.com/google/material-design-icons"',
        f'revision = "{SOURCE_REVISION}"',
        'license = "Apache-2.0"',
        f'fonttools = "{FONTTOOLS_VERSION}"',
        f"names = {len(rows)}",
        f'codepoints_sha256 = "{codepoints_sha256}"',
        'source_directory = "variablefont"',
        'modifications = "Pin GRAD=0 and opsz=24, retain FILL and wght, '
        'keep catalog codepoints, remove ligatures and hinting, and add a description."',
    ]
    codepoints = {row[2] for row in rows}
    for style in STYLES:
        source = args.source / f"{font_stem(style)}.ttf"
        output = assets / f"material-symbols-{style.lower()}.ttf"
        build_font(source, output, codepoints)
        manifest.extend([
            "",
            "[[font]]",
            f'source = "{source.name}"',
            f'source_sha256 = "{sha256(source)}"',
            f'file = "{output.name}"',
            f'sha256 = "{sha256(output)}"',
        ])
    (assets / "manifest.toml").write_text(
        "\n".join(manifest) + "\n", encoding="ascii", newline="\n"
    )


if __name__ == "__main__":
    main()
