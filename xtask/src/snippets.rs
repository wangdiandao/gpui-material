use std::{collections::BTreeSet, fmt::Write as _, fs, path::Path};

use crate::Result;

const INPUT: &str = "website/component/catalog.mjs";
const OUTPUT: &str = "crates/material/tests/catalog_snippets.rs";

#[derive(Debug, PartialEq, Eq)]
struct Snippet {
    slug: String,
    feature: Option<String>,
    imports: String,
    code: String,
}

pub(crate) fn run(check: bool) -> Result {
    let source = fs::read_to_string(INPUT)?;
    let snippets = parse_catalog(&source)?;
    let generated = generate(&snippets)?;
    if check {
        let matches = fs::read_to_string(OUTPUT)
            .is_ok_and(|current| current.replace("\r\n", "\n") == generated);
        if !matches {
            return Err(format!("{OUTPUT} is stale. Run cargo xtask snippets").into());
        }
    } else {
        if let Some(parent) = Path::new(OUTPUT).parent() {
            fs::create_dir_all(parent)?;
        }
        if !Path::new(OUTPUT).exists()
            || fs::read_to_string(OUTPUT)?.replace("\r\n", "\n") != generated
        {
            fs::write(OUTPUT, generated)?;
        }
    }
    println!(
        "Catalog snippets verified ({}, {} snippets)",
        if check { "check" } else { "generate" },
        snippets.len()
    );
    Ok(())
}

fn generate(snippets: &[Snippet]) -> Result<String> {
    if snippets.is_empty() {
        return Err("no component snippets found in catalog.mjs".into());
    }

    let mut seen = BTreeSet::new();
    let mut out = String::from(
        "// Generated by cargo xtask snippets from website/component/catalog.mjs.\n\
         // Do not edit manually; run `cargo xtask snippets` after updating catalog.mjs.\n\n\
         #![allow(dead_code, unused_imports, unused_variables)]\n\n\
         #[cfg(feature = \"full\")]\n\
         mod catalog {\n\
         \x20   use gpui::AppContext as _;\n\n\
         \x20   struct SnippetContext {\n\
         \x20       level: gpui::Entity<gpui_material::SliderState>,\n\
         \x20       host: gpui::Entity<gpui_material::SnackbarHost>,\n\
         \x20       email: gpui::Entity<gpui_material::TextFieldState>,\n\
         \x20       language: gpui::Entity<gpui_material::ExposedDropdownState>,\n\
         \x20       archive_focus: gpui::FocusHandle,\n\
         \x20       dialog: gpui::Entity<gpui_material::DialogState>,\n\
         \x20       filters: gpui::Entity<gpui_material::DialogState>,\n\
         \x20       scroll: gpui::ScrollHandle,\n\
         \x20       pane_width: gpui::Pixels,\n\
         \x20       #[cfg(feature = \"search\")]\n\
         \x20       search: gpui::Entity<gpui_material::SearchState>,\n\
         \x20       #[cfg(feature = \"date-time\")]\n\
         \x20       date: gpui::Entity<gpui_material::date_time::DatePickerState>,\n\
         \x20       #[cfg(feature = \"date-time\")]\n\
         \x20       picker: gpui::Entity<gpui_material::date_time::TimePickerState>,\n\
         \x20       #[cfg(feature = \"date-time\")]\n\
         \x20       time: gpui_material::date_time::Time,\n\
         \x20   }\n\n\
         \x20   #[rustfmt::skip]\n\
         \x20   impl SnippetContext {\n",
    );

    for snippet in snippets {
        let ident = fn_ident(&snippet.slug)?;
        if !seen.insert(ident.clone()) {
            return Err(format!("duplicate snippet slug: {}", snippet.slug).into());
        }
        if let Some(feature) = &snippet.feature {
            writeln!(out, "        #[cfg(feature = {feature:?})]")?;
        }
        writeln!(
            out,
            "        #[allow(clippy::all)]\n\
             \x20       fn {ident}(\n\
             \x20           &mut self,\n\
             \x20           window: &mut gpui::Window,\n\
             \x20           cx: &mut gpui::Context<Self>,\n\
             \x20           is_pinned: bool,\n\
             \x20           is_favorite: bool,\n\
             \x20           is_sync_enabled: bool,\n\
             \x20           is_unread_only: bool,\n\
             \x20           auto_save: bool,\n\
             \x20           selected_density: &str,\n\
             \x20           width: gpui::Pixels,\n\
             \x20           content: gpui::AnyElement,\n\
             \x20       ) {{"
        )?;
        for line in snippet.imports.lines() {
            if line.trim().is_empty() {
                out.push('\n');
            } else {
                writeln!(out, "            {line}")?;
            }
        }
        writeln!(out, "            let _ = {{")?;
        for line in snippet.code.lines() {
            if line.trim().is_empty() {
                out.push('\n');
            } else {
                writeln!(out, "                {line}")?;
            }
        }
        writeln!(out, "            }};\n        }}\n")?;
    }

    out.push_str(
        "    }\n\
         }\n\n\
         #[test]\n\
         fn all_catalog_snippets_compile() {}\n",
    );

    Ok(out)
}

fn fn_ident(slug: &str) -> Result<String> {
    if slug.is_empty()
        || !slug
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
    {
        return Err(format!("invalid component slug: {slug}").into());
    }
    Ok(format!("snippet_{}", slug.replace('-', "_")))
}

struct Parser<'a> {
    src: &'a str,
    pos: usize,
}

impl<'a> Parser<'a> {
    fn new(src: &'a str) -> Self {
        Self { src, pos: 0 }
    }

    fn rest(&self) -> &'a str {
        &self.src[self.pos..]
    }

    fn peek(&self) -> Option<u8> {
        self.src.as_bytes().get(self.pos).copied()
    }

    fn skip_ws_and_comments(&mut self) -> Result {
        loop {
            while let Some(b) = self.peek() {
                if b.is_ascii_whitespace() {
                    self.pos += 1;
                } else {
                    break;
                }
            }
            if self.rest().starts_with("//") {
                if let Some(end) = self.rest().find('\n') {
                    self.pos += end + 1;
                } else {
                    self.pos = self.src.len();
                }
            } else if self.rest().starts_with("/*") {
                let Some(end) = self.rest()[2..].find("*/") else {
                    return Err("unterminated block comment in catalog.mjs".into());
                };
                self.pos += 2 + end + 2;
            } else {
                return Ok(());
            }
        }
    }

    fn expect_byte(&mut self, expected: u8) -> Result {
        self.skip_ws_and_comments()?;
        match self.peek() {
            Some(b) if b == expected => {
                self.pos += 1;
                Ok(())
            }
            other => Err(format!(
                "expected {:?} at byte {}, found {:?}",
                expected as char,
                self.pos,
                other.map(|b| b as char)
            )
            .into()),
        }
    }

    fn parse_ident(&mut self) -> Result<String> {
        self.skip_ws_and_comments()?;
        if matches!(self.peek(), Some(b'"' | b'\'')) {
            return self.parse_string();
        }
        let start = self.pos;
        while let Some(b) = self.peek() {
            if b.is_ascii_alphanumeric() || b == b'_' || b == b'$' {
                self.pos += 1;
            } else {
                break;
            }
        }
        if self.pos == start {
            return Err(format!("expected property name at byte {}", self.pos).into());
        }
        Ok(self.src[start..self.pos].to_owned())
    }

    fn parse_string(&mut self) -> Result<String> {
        self.skip_ws_and_comments()?;
        let Some(quote) = self.peek() else {
            return Err(format!("unexpected EOF expecting string at byte {}", self.pos).into());
        };
        if !matches!(quote, b'"' | b'\'' | b'`') {
            return Err(format!(
                "expected string literal at byte {}, found {:?}",
                self.pos, quote as char
            )
            .into());
        }
        self.pos += 1;
        let mut out = String::new();
        while self.pos < self.src.len() {
            let ch = self.rest().chars().next().unwrap();
            self.pos += ch.len_utf8();
            if ch as u32 == quote as u32 {
                return Ok(out.replace("\r\n", "\n"));
            }
            if ch == '\\' {
                let Some(escaped) = self.rest().chars().next() else {
                    return Err("unterminated string escape in catalog.mjs".into());
                };
                self.pos += escaped.len_utf8();
                match escaped {
                    'n' => out.push('\n'),
                    'r' => out.push('\r'),
                    't' => out.push('\t'),
                    '\\' => out.push('\\'),
                    '"' => out.push('"'),
                    '\'' => out.push('\''),
                    '`' => out.push('`'),
                    '$' => out.push('$'),
                    other => {
                        out.push('\\');
                        out.push(other);
                    }
                }
            } else {
                out.push(ch);
            }
        }
        Err("unterminated string literal in catalog.mjs".into())
    }

    fn skip_value(&mut self) -> Result {
        self.skip_ws_and_comments()?;
        match self.peek() {
            Some(b'"' | b'\'' | b'`') => {
                let _ = self.parse_string()?;
                Ok(())
            }
            Some(b'{') => self.skip_delimited(b'{', b'}'),
            Some(b'[') => self.skip_delimited(b'[', b']'),
            Some(b'(') => self.skip_delimited(b'(', b')'),
            Some(_) => {
                while let Some(b) = self.peek() {
                    if matches!(b, b',' | b'}' | b']') {
                        break;
                    }
                    self.pos += 1;
                }
                Ok(())
            }
            None => Err("unexpected EOF while skipping JS value".into()),
        }
    }

    fn skip_delimited(&mut self, open: u8, close: u8) -> Result {
        self.expect_byte(open)?;
        let mut depth = 1usize;
        while depth > 0 {
            self.skip_ws_and_comments()?;
            match self.peek() {
                Some(b'"' | b'\'' | b'`') => {
                    let _ = self.parse_string()?;
                }
                Some(b) if b == open => {
                    self.pos += 1;
                    depth += 1;
                }
                Some(b) if b == close => {
                    self.pos += 1;
                    depth -= 1;
                }
                Some(_) => {
                    let ch = self.rest().chars().next().unwrap();
                    self.pos += ch.len_utf8();
                }
                None => return Err("unterminated delimited block in catalog.mjs".into()),
            }
        }
        Ok(())
    }

    fn parse_component(&mut self) -> Result<Snippet> {
        self.expect_byte(b'{')?;
        let mut slug = None;
        let mut feature = None;
        let mut imports = None;
        let mut code = None;

        loop {
            self.skip_ws_and_comments()?;
            if self.peek() == Some(b'}') {
                self.pos += 1;
                break;
            }
            let key = self.parse_ident()?;
            self.expect_byte(b':')?;
            match key.as_str() {
                "slug" => slug = Some(self.parse_string()?),
                "feature" => feature = Some(self.parse_string()?),
                "imports" => imports = Some(self.parse_string()?),
                "code" => code = Some(self.parse_string()?),
                _ => self.skip_value()?,
            }
            self.skip_ws_and_comments()?;
            if self.peek() == Some(b',') {
                self.pos += 1;
            }
        }

        let slug = slug.ok_or("component entry missing slug")?;
        let imports = imports.ok_or_else(|| format!("component {slug} missing imports"))?;
        let code = code.ok_or_else(|| format!("component {slug} missing code"))?;
        Ok(Snippet {
            slug,
            feature,
            imports,
            code,
        })
    }
}

fn parse_catalog(source: &str) -> Result<Vec<Snippet>> {
    let marker = "export const components =";
    let Some(start) = source.find(marker) else {
        return Err("could not find `export const components =` in catalog.mjs".into());
    };
    let mut parser = Parser::new(&source[start + marker.len()..]);
    parser.expect_byte(b'[')?;

    let mut snippets = Vec::new();
    loop {
        parser.skip_ws_and_comments()?;
        if parser.peek() == Some(b']') {
            break;
        }
        snippets.push(parser.parse_component()?);
        parser.skip_ws_and_comments()?;
        if parser.peek() == Some(b',') {
            parser.pos += 1;
        }
    }
    Ok(snippets)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_catalog_entries_with_quotes_and_templates() {
        let sample = r#"
// Header comment
export const components = [
  {
    slug: "button",
    group: "basic",
    description: { en: "Run a command.", zh: "执行命令。" },
    imports: "use gpui_material::Button;",
    code: `Button::new("save", "Save")
    .on_activate(|_, _| println!("Save"))`,
  },
  {
    slug: "window-chrome",
    feature: "window-chrome",
    story: null,
    imports: `use gpui_material::window_chrome::TitleBar;`,
    code: `TitleBar::new("bar").title("App")`,
  },
].map((guide) => ({ story: guide.slug, ...guide }));
"#;
        let parsed = parse_catalog(sample).unwrap();
        assert_eq!(parsed.len(), 2);
        assert_eq!(parsed[0].slug, "button");
        assert_eq!(parsed[0].feature, None);
        assert_eq!(parsed[1].slug, "window-chrome");
        assert_eq!(parsed[1].feature.as_deref(), Some("window-chrome"));
    }

    #[test]
    fn rejects_invalid_slug() {
        assert!(fn_ident("BadSlug").is_err());
        assert!(fn_ident("").is_err());
    }
}
